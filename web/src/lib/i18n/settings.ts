export function translateSettings(message: string, language: "en" | "zh" | "ar"): string {
  if (language === "en") return message;
  return (
    (text as Record<string, readonly [string, string]>)[message]?.[language === "zh" ? 0 : 1] ??
    message
  );
}

export function useSettingsText() {
  const { language } = useI18n();
  return (message: string): string => translateSettings(message, language);
}
